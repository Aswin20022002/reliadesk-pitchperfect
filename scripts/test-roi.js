const assert = require('assert')
const { computeRoi, REFERENCE } = require('../.test-build/roi')
const near = (a, b, tol, m) => assert.ok(Math.abs(a - b) <= tol, `${m}: got ${a}, want ${b}`)
const base = computeRoi(REFERENCE)
near(base.price / 1e7, 1.2, 0.001, 'price crore'); near(base.total / 1e7, 10.2, 0.1, 'base benefit'); near(base.multiple, 8.5, 0.1, 'base multiple'); near(base.paybackMonths, 1.4, 0.05, 'base payback')
near(base.avoidedHrs, 97.2, 0.1, 'avoided hours'); near(base.labourHrsYear, 7488, 1, 'labour hours'); near(base.breakEvenCutPct, 3.7, 0.05, 'break-even cut')
const stress = computeRoi({ ...REFERENCE, cutPct: 10, labourShare: 0.5 })
near(stress.total / 1e7, 3.5, 0.1, 'stress benefit'); near(stress.multiple, 2.9, 0.05, 'stress multiple'); near(stress.paybackMonths, 4.2, 0.05, 'stress payback')
const abb = computeRoi({ ...REFERENCE, costPerHour: 7_000_000 })
near(abb.downtimeBenefit / 1e7, 68, 0.2, 'downtime benefit at Rs 70 lakh per hour')
assert.ok(Number.isFinite(computeRoi({ ...REFERENCE, cutPct: 0, labourShare: 0 }).multiple))
console.log('ROI model reproduces the deck: price 1.2 cr, base 10.2 cr (8.5x, 1.4 months), stress 3.5 cr (2.9x, 4.2 months), break-even 3.7%, Rs 68 cr at Rs 70 lakh per hour ok')
